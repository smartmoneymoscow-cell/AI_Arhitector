def get_applicable_norms(
    building_type: str = "residential",
    floors: int = 5,
    height: float = 15.0,
    material: str = "reinforced_concrete",
    seismic_zone: str | None = None,
    soil_type: str | None = None,
) -> list[dict[str, Any]]:
    """
    Определяет перечень применимых нормативных документов по параметрам здания.

    Args:
        building_type: тип здания (residential, office, commercial, industrial, educational, medical)
        floors: количество этажей
        height: высота здания в метрах
        material: материал конструкций (reinforced_concrete, steel, masonry, timber)
        seismic_zone: сейсмический район (5, 6, 7, 8, 9) или None
        soil_type: тип грунта (I, II, III, IV) или None

    Returns:
        Список словарей с применимыми нормативными документами
    """
    result_codes = set()

    # Базовые нормы для типа здания
    type_norms = BUILDING_TYPE_NORMS.get(building_type, BUILDING_TYPE_NORMS["residential"])
    result_codes.update(type_norms)

    # Всегда нужны нагрузки и надёжность
    result_codes.add("СП 20.13330.2016")
    result_codes.add("ГОСТ 27751-2019")
    result_codes.add("ФЗ № 384-ФЗ")
    result_codes.add("ФЗ № 123-ФЗ")

    # Нормы по материалу конструкций
    material_norms = {
        "reinforced_concrete": ["СП 63.13330.2018", "ГОСТ 26434-2015"],
        "steel": ["СП 16.13330.2017", "ГОСТ 31385-2016"],
        "masonry": ["СП 15.13330.2012"],
        "timber": ["СП 64.13330.2017"],
    }
    result_codes.update(material_norms.get(material, []))

    # Фундаменты — всегда
    result_codes.add("СП 22.13330.2016")

    # Свайные фундаменты для высотных зданий или слабых грунтов
    if floors > 9 or soil_type in ("III", "IV"):
        result_codes.add("СП 24.13330.2011")

    # Сейсмика
    if seismic_zone is not None and str(seismic_zone) != "none":
        result_codes.add("СП 14.13330.2018")

    # Кровли
    result_codes.add("СП 17.13330.2017")

    # Изоляция и отделка
    result_codes.add("СП 71.13330.2017")

    # Собираем результат
    result = [norm for norm in ALL_NORMS if norm["code"] in result_codes]
    return result


def get_norm_details(norm_code: str) -> dict[str, Any] | None:
    """
    Возвращает полную информацию о нормативном документе по его коду.

    Args:
        norm_code: код документа (например, "СП 63.13330.2018")

    Returns:
        Словарь с данными документа или None, если не найден
    """
    for norm in ALL_NORMS:
        if norm["code"].lower().strip() == norm_code.lower().strip():
            return norm.copy()
    return None


def search_norms(keyword: str) -> list[dict[str, Any]]:
    """
    Поиск нормативных документов по ключевому слову.

    Ищет совпадения в коде, полном названии, категории и ключевых требованиях.

    Args:
        keyword: ключевое слово для поиска

    Returns:
        Список найденных документов
    """
    keyword_lower = keyword.lower()
    results = []
    for norm in ALL_NORMS:
        # Ищем в коде, названии, категории
        searchable = (
            norm["code"].lower()
            + " "
            + norm["full_name"].lower()
            + " "
            + norm["category"].lower()
            + " "
            + " ".join(norm["key_requirements"]).lower()
        )
        if keyword_lower in searchable:
            results.append(norm.copy())
    return results


